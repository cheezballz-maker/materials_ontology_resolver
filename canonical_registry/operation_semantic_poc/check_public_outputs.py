"""Compare public output and locally generated RDKit InChIs on the 27 controls."""
import base64,json
from pathlib import Path
from rdkit import Chem
from rdkit.Chem import inchi
H=Path(__file__).resolve().parent
d=lambda s:base64.b64decode(s).decode('utf8') if s else ''
def load(n):
 out=[]
 for line in (H/n).read_text(encoding='utf8').splitlines():
  p=line.split('\t')
  if p[0]=='R':out.append(dict(name=d(p[1]),status=p[2],message=d(p[3]),smiles=d(p[4]),cml=d(p[5]),warnings=d(p[6]),ambiguous=p[7]))
 return out
a,b=load('baseline.tsv'),load('trace.tsv');assert len(a)==len(b)==27;rows=[]
for x,y in zip(a,b):
 equality={k:x[k]==y[k] for k in ('name','status','message','smiles','cml','warnings','ambiguous')}
 z={'name':x['name'],'public_fields_equal':all(equality.values()),'inchi_status':'NOT_APPLICABLE','standard_inchi_equal':None,'fixed_h_inchi_equal':None}
 if x['smiles'] and y['smiles']:
  try:
   ma=Chem.MolFromSmiles(x['smiles']);mb=Chem.MolFromSmiles(y['smiles'])
   if ma is None or mb is None:raise ValueError('RDKit rejected output')
   ia,ib=inchi.MolToInchi(ma),inchi.MolToInchi(mb)
   fa,fb=inchi.MolToInchi(ma,options='/FixedH'),inchi.MolToInchi(mb,options='/FixedH')
   z.update(inchi_status='COMPARED',standard_inchi_equal=ia==ib,fixed_h_inchi_equal=fa==fb)
  except Exception:z['inchi_status']='UNAVAILABLE'
 rows.append(z)
out={'cases':rows,'count':len(rows),'all_public_equal':all(r['public_fields_equal'] for r in rows),'inchi_compared':sum(r['inchi_status']=='COMPARED' for r in rows),'inchi_unavailable':sum(r['inchi_status']=='UNAVAILABLE' for r in rows),'inchi_differences':sum(r['standard_inchi_equal'] is False or r['fixed_h_inchi_equal'] is False for r in rows),'note':'InChIs generated by RDKit from outputs; pinned core API itself does not provide InChI.'}
(H/'public_output_equivalence.json').write_text(json.dumps(out,indent=2),encoding='utf8');print(json.dumps({k:v for k,v in out.items() if k!='cases'},indent=2))
assert out['all_public_equal'] and out['inchi_differences']==0
